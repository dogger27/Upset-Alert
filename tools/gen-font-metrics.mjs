/*
 * Generate mobile/fontMetrics.js — per-glyph advance widths for the faces the
 * app sets player names and badges in, read from the actual TTFs.
 *
 * Why this exists: React Native cannot tell you whether a string fits without
 * drawing it, and iOS's adjustsFontSizeToFit / onTextLayout do not behave the
 * way their names suggest (the badge shrank to a speck; the name ladder never
 * stepped). Measuring from the font's own metrics is deterministic, identical
 * on iOS and in the web harness, and needs no platform cooperation.
 *
 *   node gen-font-metrics.mjs      (re-run if the app changes font or weight)
 */
import opentype from 'opentype.js'
import { readFileSync, writeFileSync } from 'node:fs'

const FONT_DIR = '../mobile/node_modules/@expo-google-fonts'

// Package per family, because the faces no longer all come from one download.
// SairaCondensed is here because the dashboard's card title is set in it and
// has to be shrunk to fit one line: measured against Archivo's tables (the
// fallback) a condensed name reads ~20% wider than it draws, and the title
// shrank to fit room it already had.
const FACES = [
  ['archivo', 'Archivo_400Regular'],
  ['archivo', 'Archivo_500Medium'],
  ['archivo', 'Archivo_700Bold'],
  ['saira-condensed', 'SairaCondensed_700Bold'],
]

/* CAP HEIGHTS, as a fraction of the em — a second, much smaller table.
 *
 * The tier badge is specified in CAP HEIGHT, not font size: its artwork was
 * cropped to the lettering and drawn `cap` tall, and the text that replaces
 * it has to land on exactly the same measure (owner, 2026-09-20, Kanit 900 /
 * 300). A font size cannot be converted to a cap height without the font's
 * own metric, and the platform will not tell you at runtime — the same
 * reason the advance widths above are generated rather than measured.
 *
 * Every face the app sets text in is listed; the per-glyph tables above stay
 * confined to the faces that need MEASURING, since each costs a few hundred
 * numbers in the bundle and a cap ratio costs one. */
const CAP_FACES = [
  ['archivo', 'Archivo_700Bold'],
  ['saira-condensed', 'SairaCondensed_700Bold'],
  ['saira-condensed', 'SairaCondensed_900Black'],
  ['kanit', 'Kanit_900Black_Italic'],
  ['kanit', 'Kanit_300Light_Italic'],
]

// Printable ASCII, Latin-1 Supplement, Latin Extended-A (Ł ł Ś ś Ž ž ļ ș …),
// plus the typographic marks that appear in names and labels.
const ranges = [[0x20, 0x7e], [0xa0, 0x17f], [0x218, 0x21b]]
const extras = '‘’–—…·'
let chars = ''
for (const [a, b] of ranges) for (let c = a; c <= b; c++) chars += String.fromCodePoint(c)
chars += extras

const out = {}
for (const [pkg, face] of FACES) {
  const dir = face.replace(/^[A-Za-z]+_/, '')
  const buf = readFileSync(`${FONT_DIR}/${pkg}/${dir}/${face}.ttf`)
  const font = opentype.parse(buf.buffer.slice(buf.byteOffset, buf.byteOffset + buf.byteLength))
  const upm = font.unitsPerEm
  const adv = []
  let present = 0, total = 0
  for (const ch of chars) {
    const g = font.charToGlyph(ch)
    // glyph 0 is .notdef: the font has no such character
    const w = g && g.index !== 0 ? g.advanceWidth : null
    adv.push(w === null ? -1 : Math.round(w))
    if (w !== null) { present++; total += w }
  }
  out[face] = { upm, chars, adv, avg: Math.round(total / present) }
  console.log(`${face}: upm ${upm}, ${present}/${chars.length} glyphs, avg ${Math.round(total / present)}`)
}

const caps = {}
for (const [pkg, face] of CAP_FACES) {
  const dir = face.replace(/^[A-Za-z]+_/, '')
  const buf = readFileSync(`${FONT_DIR}/${pkg}/${dir}/${face}.ttf`)
  const font = opentype.parse(buf.buffer.slice(buf.byteOffset, buf.byteOffset + buf.byteLength))
  // sCapHeight is the designer's own figure; a face that omits it gets the
  // measured top of its H, which is the same thing by definition.
  const declared = font.tables.os2 && font.tables.os2.sCapHeight
  const measured = font.charToGlyph('H').getBoundingBox().y2
  const cap = declared || measured
  caps[face] = Math.round((cap / font.unitsPerEm) * 1e4) / 1e4
  console.log(`${face}: cap ${cap}/${font.unitsPerEm} = ${caps[face]}`
    + (declared ? '' : ' (measured from H — no sCapHeight)'))
}

const src = `/* GENERATED by tools/gen-font-metrics.mjs — do not edit.
 * Per-glyph advance widths (font units) for the faces player names and badges
 * are set in. See mobile/measure.js for why the app measures text itself. */
export default ${JSON.stringify(out)}

/* Cap height over em, per face. The tier badge is sized in cap heights — see
 * CAP_FACES in the generator. */
export const CAP = ${JSON.stringify(caps)}
`
writeFileSync('../mobile/fontMetrics.js', src)
console.log('wrote mobile/fontMetrics.js', (src.length / 1024).toFixed(1), 'KB')
