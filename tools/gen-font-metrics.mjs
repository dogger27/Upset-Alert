/*
 * Generate mobile/fontMetrics.js — per-glyph advance widths for the faces the
 * app sets player names and badges in, read from the actual TTFs.
 *
 * Why this exists: React Native cannot tell you whether a string fits without
 * drawing it, and iOS's adjustsFontSizeToFit / onTextLayout do not behave the
 * way their names suggest (the badge shrank to a speck; the name ladder never
 * stepped). Measuring from the font's own metrics is deterministic, identical
 * on iOS and in the web harness, and needs no platform cooperation.
 *
 *   node gen-font-metrics.mjs      (re-run if the app changes font or weight)
 */
import opentype from 'opentype.js'
import { readFileSync, writeFileSync } from 'node:fs'

const FONT_DIR = '../mobile/node_modules/@expo-google-fonts/archivo'
const FACES = ['Archivo_400Regular', 'Archivo_500Medium', 'Archivo_700Bold']

// Printable ASCII, Latin-1 Supplement, Latin Extended-A (Ł ł Ś ś Ž ž ļ ș …),
// plus the typographic marks that appear in names and labels.
const ranges = [[0x20, 0x7e], [0xa0, 0x17f], [0x218, 0x21b]]
const extras = '‘’–—…·'
let chars = ''
for (const [a, b] of ranges) for (let c = a; c <= b; c++) chars += String.fromCodePoint(c)
chars += extras

const out = {}
for (const face of FACES) {
  const dir = face.replace('Archivo_', '')
  const buf = readFileSync(`${FONT_DIR}/${dir}/${face}.ttf`)
  const font = opentype.parse(buf.buffer.slice(buf.byteOffset, buf.byteOffset + buf.byteLength))
  const upm = font.unitsPerEm
  const adv = []
  let present = 0, total = 0
  for (const ch of chars) {
    const g = font.charToGlyph(ch)
    // glyph 0 is .notdef: the font has no such character
    const w = g && g.index !== 0 ? g.advanceWidth : null
    adv.push(w === null ? -1 : Math.round(w))
    if (w !== null) { present++; total += w }
  }
  out[face] = { upm, chars, adv, avg: Math.round(total / present) }
  console.log(`${face}: upm ${upm}, ${present}/${chars.length} glyphs, avg ${Math.round(total / present)}`)
}

const src = `/* GENERATED by tools/gen-font-metrics.mjs — do not edit.
 * Per-glyph advance widths (font units) for the faces player names and badges
 * are set in. See mobile/measure.js for why the app measures text itself. */
export default ${JSON.stringify(out)}
`
writeFileSync('../mobile/fontMetrics.js', src)
console.log('wrote mobile/fontMetrics.js', (src.length / 1024).toFixed(1), 'KB')
